// config.yaml is the gateway's single source of settings. Environment variables
// seed it on first start only (see resolveConfig); afterwards the file wins and
// a differing env var is reported, never applied. The file is always at
// configFilePath; no setting moves it, and neither the users store, the
// connections store nor the store key: they are always at their default paths
// (below), so the settings an administrator changes from the console can never
// point the gateway at a different secret or store. Moving data is Backup &
// Restore. Nobody edits the file by hand: the header it is written with says so.
const (
	configVersion          = 1
	configFilePath         = "/data/config.yaml" // fixed, like appRoot
	defaultUsersFile       = "/data/users.yaml"
	defaultConnectionsFile = "/data/connections.yaml"
	defaultStoreKeyFile    = "/data/store.key"
	defaultAuditFile       = "/data/audit.log"
)

const configFileHeader = `# config.yaml -- AUTHORITATIVE gateway settings.
# Written by the gateway. Do not edit this file by hand.
# Environment variables seed this file on first start only, when it does not
# exist. Afterwards the file wins; a changed env var is ignored and logged.
# To seed it again from env, delete it and start the gateway.
# In Provisioned mode an administrator changes these settings on the admin
# console's Gateway Settings page, where they apply at once, and carries them
# to another deployment with Backup & Restore. hosted is read at start only.
# access.*, session.*, login.*, modules.*, audit.access and audit.onFailure have
# no env var: they start at their defaults. audit.stdout is seeded by
# SMU_SHOW_AUDIT.
# audit.onFailure (continue|refuse) says what happens when an audit record
# cannot be written: continue logs it loudly and carries on; refuse also
# refuses changes until the audit log is writable again.
# login.twoFactor (optional|admins|mandatory) says who signs in with a code
# from an authenticator app as well as the password: those who set it up, those
# plus every administrator who has not, or everyone. It cannot be switched off.
# An empty allow list admits every client; trustedProxies lists the reverse
# proxies whose X-Forwarded-For is believed. session.*, login.*, modules.* and
# audit.* apply only in Provisioned mode (connModes provisioned or both):
# modules.offered lists the app modules a signed-in user may be given,
# modules.userDefault (all|none) what a user without a list of their own gets.
# The TLS paths are not settings: SMU_SSL_CERTFILE, SMU_SSL_CERTKEYFILE and
# SMU_SSL_TRUSTDIR are read from the environment at every start. An old
# tls.certFile, tls.keyFile or tls.trustDir key is ignored and dropped at the
# next save. The certificate and the trusted CAs change live from the admin
# console's Certificates page, and tls.insecureSkipVerify applies at once.
`

// fileConfig is the on-disk shape. Field order is the order yaml.Marshal writes.
// The JSON names are the settings page's (GET/PUT /managed/settings): the same
// keys, without the version, which the gateway owns.
type fileConfig struct {
	Version     int         `yaml:"version" json:"-"`
	Hosted      bool        `yaml:"hosted" json:"hosted"`
	ConnModes   string      `yaml:"connModes" json:"connModes"`
	DefaultConn string      `yaml:"defaultConn" json:"defaultConn"`
	TLS         fileTLS     `yaml:"tls" json:"tls"`
	LogLevel    string      `yaml:"logLevel" json:"logLevel"`
	Access      fileAccess  `yaml:"access" json:"access"`
	Session     fileSession `yaml:"session" json:"session"`
	Login       fileLogin   `yaml:"login" json:"login"`
	Modules     fileModules `yaml:"modules" json:"modules"`
	Audit       fileAudit   `yaml:"audit" json:"audit"`
	// RemovedAppDir is the appDir key an earlier release read; the app is now
	// always served from appRoot. A file that still has it loads, the value is
	// ignored with a warning at start (removedInUse), and the gateway's next
	// write of the file drops it. The same holds for the usersFile and
	// connectionsFile keys: the stores are always at their default paths, and
	// for tls.certFile, tls.keyFile and tls.trustDir (fileTLS).
	RemovedAppDir          *string `yaml:"appDir,omitempty" json:"-"`
	RemovedUsersFile       *string `yaml:"usersFile,omitempty" json:"-"`
	RemovedConnectionsFile *string `yaml:"connectionsFile,omitempty" json:"-"`
}

// fileTLS is the tls block. The certificate, key and trust directory paths are
// environment only (tlsPaths); an earlier release kept them here, so a file or
// backup that still has them loads, they are ignored with one warning at start
// (removedTLSPaths) and the next write of the file drops them.
type fileTLS struct {
	InsecureSkipVerify bool    `yaml:"insecureSkipVerify" json:"insecureSkipVerify"`
	RemovedCertFile    *string `yaml:"certFile,omitempty" json:"-"`
	RemovedKeyFile     *string `yaml:"keyFile,omitempty" json:"-"`
	RemovedTrustDir    *string `yaml:"trustDir,omitempty" json:"-"`
}

// tlsPaths are where the gateway keeps its certificate, its key and the CA
// directory. They come from the environment at every start (tlsPathsFromEnv),
// never from config.yaml or the settings page.
type tlsPaths struct {
	certFile, keyFile, trustDir string
}

const (
	defaultCertFile = "/tls/tls.crt"
	defaultKeyFile  = "/tls/tls.key"
	defaultTrustDir = "/tls/trust"
)

// tlsPathsFromEnv reads SMU_SSL_CERTFILE, SMU_SSL_CERTKEYFILE and
// SMU_SSL_TRUSTDIR, with the image's defaults for any that is unset.
func tlsPathsFromEnv() tlsPaths {
	return tlsPaths{
		certFile: envOr("SMU_SSL_CERTFILE", defaultCertFile),
		keyFile:  envOr("SMU_SSL_CERTKEYFILE", defaultKeyFile),
		trustDir: envOr("SMU_SSL_TRUSTDIR", defaultTrustDir),
	}
}

type fileAccess struct {
	Allow          []string `yaml:"allow" json:"allow"`
	TrustedProxies []string `yaml:"trustedProxies" json:"trustedProxies"`
}

type fileSession struct {
	IdleMinutes       int `yaml:"idleMinutes" json:"idleMinutes"`
	AbsoluteMinutes   int `yaml:"absoluteMinutes" json:"absoluteMinutes"`
	ConnectsPerMinute int `yaml:"connectsPerMinute" json:"connectsPerMinute"`
}

type fileLogin struct {
	MaxFailures              int  `yaml:"maxFailures" json:"maxFailures"` // per account
	PerClient                bool `yaml:"perClient" json:"perClient"`
	ClientMaxFailures        int  `yaml:"clientMaxFailures" json:"clientMaxFailures"`
	ResetMinutes             int  `yaml:"resetMinutes" json:"resetMinutes"`
	BackoffSeconds           int  `yaml:"backoffSeconds" json:"backoffSeconds"`
	MaxBackoffSeconds        int  `yaml:"maxBackoffSeconds" json:"maxBackoffSeconds"`
	UnauthenticatedPerMinute int  `yaml:"unauthenticatedPerMinute" json:"unauthenticatedPerMinute"`
	PasswordMinLength        int  `yaml:"passwordMinLength" json:"passwordMinLength"`
	TwoFactorMinutes         int  `yaml:"twoFactorMinutes" json:"twoFactorMinutes"`
	// TwoFactor is optional (the default, also for a file or backup without
	// the key), admins or mandatory (totp.go). Live.
	TwoFactor string `yaml:"twoFactor" json:"twoFactor"`
}

type fileModules struct {
	Offered     []string `yaml:"offered" json:"offered"`
	UserDefault string   `yaml:"userDefault" json:"userDefault"`
}

// fileAudit holds the audit stream's options (audit.go). All apply at the next
// event; the log file itself is always on in Provisioned mode. OnFailure is
// continue (the default, also for a file without the key) or refuse.
type fileAudit struct {
	Stdout    bool   `yaml:"stdout" json:"stdout"`
	Access    bool   `yaml:"access" json:"access"`
	OnFailure string `yaml:"onFailure" json:"onFailure"`
}

// clone copies fc deeply enough that decoding into the copy cannot write
// through to fc's slices.
func (fc fileConfig) clone() fileConfig {
	fc.Access.Allow = slices.Clone(fc.Access.Allow)
	fc.Access.TrustedProxies = slices.Clone(fc.Access.TrustedProxies)
	fc.Modules.Offered = slices.Clone(fc.Modules.Offered)
	return fc
}

// sessionLimits bound a Provisioned sign-in session: idle is measured from the
// last request, absolute from sign-in (session.go).
type sessionLimits struct {
	idle, absolute time.Duration
	// ticket is login.twoFactorMinutes: how long a sign-in that passed the
	// password waits for its two-factor step; 0 means defaultTicketTTL.
	ticket time.Duration
	// connects is session.connectsPerMinute: credential requests plus SMF
	// sockets opened per user per minute; 0 means defaultConnectsPerMinute.
	connects int
}

// ticketTTL is how long a half-finished sign-in waits for its next step.
func (l sessionLimits) ticketTTL() time.Duration {
	if l.ticket > 0 {
		return l.ticket
	}
	return defaultTicketTTL
}

// connectsPerMinute is how many credential requests and SMF sockets one user
// may open in a minute.
func (l sessionLimits) connectsPerMinute() int {
	if l.connects > 0 {
		return l.connects
	}
	return defaultConnectsPerMinute
}

// loginLimits drive the sign-in throttle (throttle.go): back-off after
// maxFailures failed sign-ins, doubling from backoff up to maxBackoff, and a
// per-client budget for requests that carry no session.
type loginLimits struct {
	maxFailures     int // per account
	backoff         time.Duration
	maxBackoff      time.Duration
	unauthPerMinute int
	// perClientOff is login.perClient turned off: failures are counted per
	// account only, for a deployment where every user reaches the gateway
	// from one address. Inverted so the zero value keeps per-client counting.
	perClientOff bool
	// clientMaxFailures is login.clientMaxFailures; 0 means maxFailures.
	clientMaxFailures int
	// reset is login.resetMinutes, how long a count is kept without a new
	// failure; 0 means maxBackoff.
	reset time.Duration
	// passwordMinLength is login.passwordMinLength; 0 means passwordMinLen.
	passwordMinLength int
}

// clientThreshold is the failures a client may make before its back-off.
func (l loginLimits) clientThreshold() int {
	if l.clientMaxFailures > 0 {
		return l.clientMaxFailures
	}
	return l.maxFailures
}

// resetAfter is how long a failure count is kept without a new failure.
func (l loginLimits) resetAfter() time.Duration {
	if l.reset > 0 {
		return l.reset
	}
	return l.maxBackoff
}

// minPassword is the shortest password a user may set.
func (l loginLimits) minPassword() int {
	if l.passwordMinLength > 0 {
		return l.passwordMinLength
	}
	return passwordMinLen
}

// moduleCatalog is every app module an administrator can give a signed-in user.
// The sign-in module (connections) is always shown and the admin modules live
// in the admin app, so neither is listed. Queue Subscription Explorer reads the
// broker's whole subscription list over SEMP v1 and filters it to the user's
// provisioned VPNs and visible queues in the browser (visibleQueueRows in
// src/core/managed-semp-filter.ts), like the queue lists. Queue Discovery is
// left out: nothing filters it, so it stays hidden in every Provisioned
// session (src/core/rbac.ts). tests/variants.test.ts parses this line and
// checks it against the managed variant.
func moduleCatalog() []string {
	return []string{"queue-browser", "queue-copy", "queue-subscription-explorer"}
}

// modules.userDefault values: what a user without a list of their own gets.
const (
	modulesDefaultAll  = "all"
	modulesDefaultNone = "none"
)

// moduleSettings is the validated modules block. offered is in catalog order.
type moduleSettings struct {
	offered     []string
	userDefault string
}

// forUser is the modules a user may open: their own list, or the deployment
// default when they have none, never beyond what is offered. granted nil means
// "no list of their own"; an empty list means none.
func (ms moduleSettings) forUser(granted *[]string) []string {
	out := []string{}
	for _, id := range ms.offered {
		if granted == nil && ms.userDefault == modulesDefaultAll || granted != nil && slices.Contains(*granted, id) {
			out = append(out, id)
		}
	}
	return out
}

// checkModuleIDs rejects an id outside the catalog and one listed twice; key
// names the list in the error.
func checkModuleIDs(key string, ids []string) error {
	catalog := moduleCatalog()
	for i, id := range ids {
		at := fmt.Sprintf("%s[%d]", key, i)
		if !slices.Contains(catalog, id) {
			return fmt.Errorf("key %q has invalid value %q: must be one of %s", at, id, strings.Join(catalog, ", "))
		}
		if slices.Index(ids, id) < i {
			return fmt.Errorf("key %q has invalid value %q: listed twice", at, id)
		}
	}
	return nil
}

// seedVar maps one environment variable to its config.yaml key. fromEnv
// normalises the raw env string the way loadConfig parses it, so the override
// comparison is on effective values; a value loadConfig would refuse (such as
// SMU_SSL_SKIP_CERT_VERIFY=TRUE) stays as typed and is reported as differing.
type seedVar struct {
	env, key  string
	fromEnv   func(raw string) string
	fileValue func(c config) string
}

var seedVars = []seedVar{
	{"SMU_HOSTED", "hosted", hostedEnv, func(c config) string { return strconv.FormatBool(c.hosted) }},
	{"SMU_CONN_MODES", "connModes", strings.ToLower, func(c config) string { return c.connModes }},
	{"SMU_DEFAULT_CONN", "defaultConn", strings.ToLower, func(c config) string { return c.defaultConn }},
	{"SMU_SSL_SKIP_CERT_VERIFY", "tls.insecureSkipVerify", insecureEnv, func(c config) string { return strconv.FormatBool(c.insecureSkipVerify) }},
	{"LOG_LEVEL", "logLevel", strings.ToLower, func(c config) string { return levelName(c.logLevel) }},
	{"SMU_SHOW_AUDIT", "audit.stdout", showAuditEnv, func(c config) string { return strconv.FormatBool(c.audit.stdout) }},
}

// renamedEnv are the variables an earlier release read, with their names now.
// SSL_CERT_FILE is the one that forced the rename: Go itself reads it as its
// CA bundle, so the old name silently replaced the upstream trust pool. A
// start with any of them set is refused (checkRenamedEnv), so a stale name
// can never be mistaken for a setting that applies.
var renamedEnv = []struct{ old, new string }{
	{"SSL_CERT_FILE", "SMU_SSL_CERTFILE"},
	{"SSL_KEY_FILE", "SMU_SSL_CERTKEYFILE"},
	{"SSL_TRUST_DIR", "SMU_SSL_TRUSTDIR"},
	{"SSL_INSECURE_SKIP_VERIFY", "SMU_SSL_SKIP_CERT_VERIFY"},
	{"HOSTED", "SMU_HOSTED"},
	{"CONN_MODES", "SMU_CONN_MODES"},
	{"DEFAULT_CONN", "SMU_DEFAULT_CONN"},
	{"ADMIN_PASSWORD", "SMU_ADMIN_PASSWORD"},
	{"ADMIN_PASSWORD_FILE", "SMU_ADMIN_PASSWORD_FILE"},
}

// checkRenamedEnv refuses a start with an old variable name set. One error
// lists every old name found and its new name; values are never printed
// (ADMIN_PASSWORD is a secret).
func checkRenamedEnv() error {
	var found []string
	for _, r := range renamedEnv {
		if os.Getenv(r.old) != "" {
			found = append(found, r.old+" -> "+r.new)
		}
	}
	if len(found) == 0 {
		return nil
	}
	return fmt.Errorf("environment variables renamed, so the gateway will not start with the old names set: %s. Rename them in the deployment (same values) and start again", strings.Join(found, ", "))
}

// insecureEnv mirrors parseInsecureSkipVerify for the override comparison,
// as hostedEnv mirrors parseHosted.
func insecureEnv(raw string) string {
	if b, err := parseInsecureSkipVerify(raw); err == nil {
		return strconv.FormatBool(b)
	}
	return raw
}

// showAuditEnv mirrors parseShowAudit for the override comparison.
func showAuditEnv(raw string) string {
	if b, err := parseShowAudit(raw); err == nil {
		return strconv.FormatBool(b)
	}
	return raw
}

// hostedEnv mirrors parseHosted for the override comparison: unset or "true" is
// true, "false" is false, and any other value stays as typed, so it is
// reported as differing from the file.
func hostedEnv(raw string) string {
	if b, err := parseHosted(raw); err == nil {
		return strconv.FormatBool(b)
	}
	return raw
}

// secretPaths are the locations of the gateway's secrets and its TLS files.
// toConfig takes them from its caller, never from the file.
type secretPaths struct {
	storeKey string
	tls      tlsPaths
}

func defaultSecretPaths() secretPaths {
	return secretPaths{storeKey: defaultStoreKeyFile, tls: tlsPathsFromEnv()}
}

// secretPaths are the paths c runs with, for a config rebuilt from a document
// that does not hold them (a settings save, an import).
func (c config) secretPaths() secretPaths {
	return secretPaths{storeKey: c.storeKeyFile, tls: tlsPaths{certFile: c.certFile, keyFile: c.keyFile, trustDir: c.trustDir}}
}

func defaultFileConfig() fileConfig { return fileConfigFromConfig(defaultConfig()) }

func fileConfigFromConfig(c config) fileConfig {
	return fileConfig{
		Version:     configVersion,
		Hosted:      c.hosted,
		ConnModes:   c.connModes,
		DefaultConn: c.defaultConn,
		TLS:         fileTLS{InsecureSkipVerify: c.insecureSkipVerify},
		LogLevel:    levelName(c.logLevel),
		Access: fileAccess{
			Allow:          prefixStrings(c.access.allow),
			TrustedProxies: prefixStrings(c.access.trustedProxies),
		},
		Session: fileSession{
			IdleMinutes:       int(c.session.idle / time.Minute),
			AbsoluteMinutes:   int(c.session.absolute / time.Minute),
			ConnectsPerMinute: c.session.connectsPerMinute(),
		},
		Login: fileLogin{
			MaxFailures:              c.login.maxFailures,
			PerClient:                !c.login.perClientOff,
			ClientMaxFailures:        c.login.clientThreshold(),
			ResetMinutes:             int(c.login.resetAfter() / time.Minute),
			BackoffSeconds:           int(c.login.backoff / time.Second),
			MaxBackoffSeconds:        int(c.login.maxBackoff / time.Second),
			UnauthenticatedPerMinute: c.login.unauthPerMinute,
			PasswordMinLength:        c.login.minPassword(),
			TwoFactorMinutes:         int(c.session.ticketTTL() / time.Minute),
			TwoFactor:                twoFactorOrDefault(c.twoFactor),
		},
		Modules: fileModules{
			Offered:     append([]string{}, c.modules.offered...),
			UserDefault: c.modules.userDefault,
		},
		Audit: fileAudit{Stdout: c.audit.stdout, Access: c.audit.access, OnFailure: onFailureOrDefault(c.audit.onFailure)},
	}
}

// onFailureOrDefault is the audit.onFailure a config holds: the zero value of
// a config built without it is the default.
func onFailureOrDefault(v string) string {
	if v == "" {
		return auditOnFailureContinue
	}
	return v
}

func prefixStrings(ps []netip.Prefix) []string {
	out := make([]string, 0, len(ps))
	for _, p := range ps {
		out = append(out, p.String())
	}
	return out
}

// toConfig validates every value and converts to the runtime config.
// The stores, the secret paths and the TLS paths are never read from the file.
func (fc fileConfig) toConfig(secrets secretPaths) (config, error) {
	level, err := parseLogLevel(fc.LogLevel)
	if err != nil {
		return config{}, fmt.Errorf("key %q has invalid value %q: %w", "logLevel", fc.LogLevel, err)
	}
	allow, err := parseCIDRs("access.allow", fc.Access.Allow)
	if err != nil {
		return config{}, err
	}
	trusted, err := parseCIDRs("access.trustedProxies", fc.Access.TrustedProxies)
	if err != nil {
		return config{}, err
	}
	session, err := fc.Session.limits()
	if err != nil {
		return config{}, err
	}
	login, err := fc.Login.limits()
	if err != nil {
		return config{}, err
	}
	// login.twoFactorMinutes is a sign-in setting, kept beside the session
	// limits because the sign-in tickets live with the sessions.
	if err := intInRange("login.twoFactorMinutes", fc.Login.TwoFactorMinutes, 1, 60); err != nil {
		return config{}, err
	}
	session.ticket = time.Duration(fc.Login.TwoFactorMinutes) * time.Minute
	modules, err := fc.Modules.settings()
	if err != nil {
		return config{}, err
	}
	onFailure, err := checkAuditOnFailure(fc.Audit.OnFailure)
	if err != nil {
		return config{}, err
	}
	twoFactor, err := checkTwoFactor(fc.Login.TwoFactor)
	if err != nil {
		return config{}, err
	}
	cfg := config{
		hosted:             fc.Hosted,
		certFile:           secrets.tls.certFile,
		keyFile:            secrets.tls.keyFile,
		trustDir:           secrets.tls.trustDir,
		insecureSkipVerify: fc.TLS.InsecureSkipVerify,
		logLevel:           level,
		usersFile:          defaultUsersFile,
		connectionsFile:    defaultConnectionsFile,
		storeKeyFile:       secrets.storeKey,
		backupDir:          backupRoot,
		auditFile:          defaultAuditFile,
		connModes:          strings.ToLower(fc.ConnModes),
		defaultConn:        strings.ToLower(fc.DefaultConn),
		access:             accessConfig{allow: allow, trustedProxies: trusted},
		session:            session,
		login:              login,
		twoFactor:          twoFactor,
		modules:            modules,
		audit:              auditSettings{stdout: fc.Audit.Stdout, access: fc.Audit.Access, onFailure: onFailure},
	}
	// Value and cross checks on the connection modes.
	if err := validateConnModes(cfg); err != nil {
		return config{}, err
	}
	return cfg, nil
}

// limits validates the session block. The upper bound keeps a session from
// outliving a day; idle can never exceed absolute.
func (sc fileSession) limits() (sessionLimits, error) {
	if err := intInRange("session.absoluteMinutes", sc.AbsoluteMinutes, 1, 1440); err != nil {
		return sessionLimits{}, err
	}
	if err := intInRange("session.idleMinutes", sc.IdleMinutes, 1, sc.AbsoluteMinutes); err != nil {
		return sessionLimits{}, fmt.Errorf("%w (session.absoluteMinutes is %d)", err, sc.AbsoluteMinutes)
	}
	if err := intInRange("session.connectsPerMinute", sc.ConnectsPerMinute, 1, 1000); err != nil {
		return sessionLimits{}, err
	}
	return sessionLimits{
		idle:     time.Duration(sc.IdleMinutes) * time.Minute,
		absolute: time.Duration(sc.AbsoluteMinutes) * time.Minute,
		connects: sc.ConnectsPerMinute,
	}, nil
}

// limits validates the login block; maxBackoffSeconds can never be below
// backoffSeconds. The minimum password length never goes below the built-in
// one, so the setting can only tighten the rule.
func (fl fileLogin) limits() (loginLimits, error) {
	checks := []struct {
		key       string
		v, lo, hi int
	}{
		{"login.maxFailures", fl.MaxFailures, 1, 1000},
		{"login.clientMaxFailures", fl.ClientMaxFailures, 1, 1000},
		{"login.resetMinutes", fl.ResetMinutes, 1, 1440},
		{"login.maxBackoffSeconds", fl.MaxBackoffSeconds, 1, 86400},
		{"login.unauthenticatedPerMinute", fl.UnauthenticatedPerMinute, 1, 10000},
		{"login.passwordMinLength", fl.PasswordMinLength, passwordMinLen, passwordMaxLen},
	}
	for _, c := range checks {
		if err := intInRange(c.key, c.v, c.lo, c.hi); err != nil {
			return loginLimits{}, err
		}
	}
	if err := intInRange("login.backoffSeconds", fl.BackoffSeconds, 1, fl.MaxBackoffSeconds); err != nil {
		return loginLimits{}, fmt.Errorf("%w (login.maxBackoffSeconds is %d)", err, fl.MaxBackoffSeconds)
	}
	return loginLimits{
		maxFailures:       fl.MaxFailures,
		backoff:           time.Duration(fl.BackoffSeconds) * time.Second,
		maxBackoff:        time.Duration(fl.MaxBackoffSeconds) * time.Second,
		unauthPerMinute:   fl.UnauthenticatedPerMinute,
		perClientOff:      !fl.PerClient,
		clientMaxFailures: fl.ClientMaxFailures,
		reset:             time.Duration(fl.ResetMinutes) * time.Minute,
		passwordMinLength: fl.PasswordMinLength,
	}, nil
}

// settings validates the modules block.
func (fm fileModules) settings() (moduleSettings, error) {
	if err := checkModuleIDs("modules.offered", fm.Offered); err != nil {
		return moduleSettings{}, err
	}
	switch fm.UserDefault {
	case modulesDefaultAll, modulesDefaultNone:
	default:
		return moduleSettings{}, fmt.Errorf("key %q has invalid value %q: must be %q or %q", "modules.userDefault", fm.UserDefault, modulesDefaultAll, modulesDefaultNone)
	}
	offered := []string{}
	for _, id := range moduleCatalog() {
		if slices.Contains(fm.Offered, id) {
			offered = append(offered, id)
		}
	}
	return moduleSettings{offered: offered, userDefault: fm.UserDefault}, nil
}

func intInRange(key string, v, lo, hi int) error {
	if v < lo || v > hi {
		return fmt.Errorf("key %q has invalid value %q: must be %d to %d", key, strconv.Itoa(v), lo, hi)
	}
	return nil
}

// parseCIDRs turns the file's CIDR strings into masked prefixes. A bare address
// is rejected (ParsePrefix needs the slash) and so is an IPv4-mapped IPv6
// prefix, which would never match the unmapped addresses the access check
// compares against.
func parseCIDRs(key string, in []string) ([]netip.Prefix, error) {
	if len(in) == 0 {
		return nil, nil
	}
	out := make([]netip.Prefix, 0, len(in))
	for i, s := range in {
		at := fmt.Sprintf("%s[%d]", key, i)
		p, err := netip.ParsePrefix(strings.TrimSpace(s))
		if err != nil {
			return nil, fmt.Errorf("key %q has invalid value %q: want CIDR such as 10.0.0.0/8 or 192.0.2.7/32 (%v)", at, s, err)
		}
		if p.Addr().Is4In6() {
			return nil, fmt.Errorf("key %q has invalid value %q: use the IPv4 form", at, s)
		}
		out = append(out, p.Masked())
	}
	return out, nil
}

// decodeConfigFile parses a config file strictly: unknown keys, an empty file
// and a foreign version are errors. Missing keys keep their built-in defaults
// (never an env value: the file is authoritative).
func decodeConfigFile(data []byte, path string) (fileConfig, error) {
	fc := defaultFileConfig()
	fc.Version = 0 // the file must say so itself
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(&fc); err != nil {
		if errors.Is(err, io.EOF) {
			return fileConfig{}, fmt.Errorf("config file %q is empty; delete it to re-seed from the environment", path)
		}
		return fileConfig{}, fmt.Errorf("invalid config file %q: %w", path, err)
	}
	if fc.Version != configVersion {
		return fileConfig{}, fmt.Errorf("config file %q: version=%d unsupported, this gateway reads version %d; delete it to re-seed from the environment", path, fc.Version, configVersion)
	}
	return fc, nil
}

// encodeConfigFile renders the file the gateway writes on first start: the
// fixed header, the key-to-env table (generated from seedVars so it cannot
// drift), then the marshalled settings.
func encodeConfigFile(fc fileConfig) ([]byte, error) {
	body, err := yaml.Marshal(fc)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(configFileHeader)
	b.WriteString("# Key <- seeding environment variable:\n")
	for _, v := range seedVars {
		fmt.Fprintf(&b, "#   %s <- %s\n", v.key, v.env)
	}
	b.Write(body)
	return b.Bytes(), nil
}

// envOverride is one seeding variable that is set but disagrees with the file.
type envOverride struct{ Env, Key, EnvValue, FileValue string }

type configLoad struct {
	cfg       config
	seeded    bool
	overrides []envOverride
	removed   []removedSetting // still set (removedInUse); ignored
	data      []byte           // the bytes of the file as read or seeded
	// tlsPathsIgnored names the TLS path keys the file still holds whose value
	// differs from the path in use (removedTLSPaths); ignored.
	tlsPathsIgnored []string
}

// removedSetting is a setting an earlier release read that the file or the
// environment still sets.
type removedSetting struct {
	name    string // the key or the variable
	instead string // what replaced it, for the warning
}

// removedInUse names the removed settings still set. They are accepted and
// ignored, so an upgrade never fails on them; serve warns about each. A
// CONFIG_FILE naming another file never gets here: resolveConfig refuses it.
func removedInUse(fc fileConfig) []removedSetting {
	const ownBuild = "to serve your own build, mount it at " + appRoot
	const moveData = "; to move data use Backup & Restore"
	var out []removedSetting
	if fc.RemovedAppDir != nil {
		out = append(out, removedSetting{"appDir", ownBuild})
	}
	if os.Getenv("APP_DIR") != "" {
		out = append(out, removedSetting{"APP_DIR", ownBuild})
	}
	if os.Getenv("CONFIG_FILE") != "" {
		out = append(out, removedSetting{"CONFIG_FILE", "config.yaml is always " + configFilePath})
	}
	usersNow := "the users store is always " + defaultUsersFile + moveData
	connsNow := "the connections store is always " + defaultConnectionsFile + moveData
	if fc.RemovedUsersFile != nil {
		out = append(out, removedSetting{"usersFile", usersNow})
	}
	if os.Getenv("USERS_FILE") != "" {
		out = append(out, removedSetting{"USERS_FILE", usersNow})
	}
	if fc.RemovedConnectionsFile != nil {
		out = append(out, removedSetting{"connectionsFile", connsNow})
	}
	if os.Getenv("CONNECTIONS_FILE") != "" {
		out = append(out, removedSetting{"CONNECTIONS_FILE", connsNow})
	}
	if os.Getenv("STORE_KEY_FILE") != "" {
		out = append(out, removedSetting{"STORE_KEY_FILE", "the store key is always " + defaultStoreKeyFile + moveData})
	}
	return out
}

// removedTLSPaths names the tls.certFile, tls.keyFile and tls.trustDir keys fc
// still holds whose value differs from the path in use, as `key="value" (in
// use: "path")`. A key that agrees with the environment says nothing: it
// changes nothing. serve logs them in one warning.
func removedTLSPaths(fc fileConfig, inUse tlsPaths) []string {
	var out []string
	for _, k := range []struct {
		key   string
		value *string
		path  string
	}{
		{"tls.certFile", fc.TLS.RemovedCertFile, inUse.certFile},
		{"tls.keyFile", fc.TLS.RemovedKeyFile, inUse.keyFile},
		{"tls.trustDir", fc.TLS.RemovedTrustDir, inUse.trustDir},
	} {
		if k.value != nil && *k.value != k.path {
			out = append(out, fmt.Sprintf("%s=%q (in use: %q)", k.key, *k.value, k.path))
		}
	}
	return out
}

// configSource is where the running config came from: the file and the bytes
// the gateway read or seeded. newSettingsFile hands them to the writer's
// checksums, so the settings rev and the changed-on-disk check start from what
// was loaded, not from what the file holds by the time the stores are up.
type configSource struct {
	path string
	data []byte
}

// resolveConfig loads config.yaml, seeding it from the environment when it does
// not exist yet. Every failure is fatal for the caller and names the path.
func resolveConfig(path string) (configLoad, error) {
	// An old variable name stops the start before anything is read or written.
	if err := checkRenamedEnv(); err != nil {
		return configLoad{}, err
	}
	// CONFIG_FILE is no longer read. One that still names another file stops
	// the start: seeding a fresh file instead would drop that file's settings,
	// the access list among them, without a word.
	if v := os.Getenv("CONFIG_FILE"); v != "" && filepath.Clean(v) != filepath.Clean(path) {
		return configLoad{}, fmt.Errorf("CONFIG_FILE=%q is no longer read: config.yaml is always %s. Move the file there and remove CONFIG_FILE", v, path)
	}
	secrets := defaultSecretPaths()
	data, err := os.ReadFile(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		envCfg, err := loadConfig()
		if err != nil {
			return configLoad{}, fmt.Errorf("cannot seed config file %q from the environment: %w", path, err)
		}
		// Validate before writing, so a rejected value never lands in the file.
		cfg, err := fileConfigFromConfig(envCfg).toConfig(secrets)
		if err != nil {
			return configLoad{}, fmt.Errorf("cannot seed config file %q from the environment: %w", path, err)
		}
		seeded, err := seedConfigFile(path, cfg)
		if err != nil {
			return configLoad{}, err
		}
		return configLoad{cfg: cfg, seeded: true, removed: removedInUse(fileConfig{}), data: seeded}, nil
	case err != nil:
		return configLoad{}, fmt.Errorf("cannot read config file %q: %w", path, err)
	}
	fc, err := decodeConfigFile(data, path)
	if err != nil {
		return configLoad{}, err
	}
	cfg, err := fc.toConfig(secrets)
	if err != nil {
		return configLoad{}, fmt.Errorf("config file %q: %w", path, err)
	}
	return configLoad{cfg: cfg, overrides: envOverrides(cfg), removed: removedInUse(fc), tlsPathsIgnored: removedTLSPaths(fc, secrets.tls), data: data}, nil
}

// seedConfigFile writes the first config.yaml and returns the bytes it wrote.
// Readable by operators (0644): it holds no secret. It goes through the
// journaled commit like every other write of the file, on a writer of its own:
// this runs at start, before the store key is loaded, so there is no checksum
// to keep and nothing else to exclude.
func seedConfigFile(path string, cfg config) ([]byte, error) {
	data, err := encodeConfigFile(fileConfigFromConfig(cfg))
	if err != nil {
		return nil, fmt.Errorf("cannot encode config file %q: %w", path, err)
	}
	wr := newWriter(filepath.Dir(path), nil, nil)
	err = wr.Do(context.Background(), func(tx *txn) error {
		tx.stage(path, data, 0o644, configVerifier(path))
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("cannot write config file %q: %w. The gateway creates it on first start. Fix: make the directory writable by the gateway user (UID 65532), e.g. mount a writable volume at /data", path, err)
	}
	return data, nil
}

// configVerifier is the round-trip check of every config.yaml commit: the
// bytes read back from the temp file must parse as strictly as a start would
// parse them. config.yaml holds no secret, so the parse error is shown whole.
func configVerifier(path string) func([]byte) error {
	return func(data []byte) error {
		_, err := decodeConfigFile(data, path)
		return err
	}
}

// envOverrides lists the seeding variables that are set but disagree with the
// file. They are reported, never applied: the file is authoritative.
func envOverrides(file config) []envOverride {
	var out []envOverride
	for _, v := range seedVars {
		raw := os.Getenv(v.env)
		if raw == "" {
			continue
		}
		fv := v.fileValue(file)
		if v.fromEnv(raw) == fv {
			continue
		}
		out = append(out, envOverride{Env: v.env, Key: v.key, EnvValue: raw, FileValue: fv})
	}
	return out
}

// levelName is the inverse of parseLogLevel for the four levels the file accepts.
func levelName(l slog.Level) string {
	switch l {
	case slog.LevelDebug:
		return "debug"
	case slog.LevelInfo:
		return "info"
	case slog.LevelWarn:
		return "warn"
	case slog.LevelError:
		return "error"
	}
	return strings.ToLower(l.String())
}
